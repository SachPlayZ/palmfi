#!/usr/bin/env node
// Exports contract ABIs from contracts/out (run `forge build` in contracts/ first) into web/src/abi/*.ts.
// Usage (from web/): pnpm abi
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "../../contracts/out");
const dest = join(here, "../src/abi");
const contracts = ["Vault", "VaultFactory", "Hub", "ApprovalBook", "NetworkRegistry", "ProtectedToken"];

if (!existsSync(out)) {
  console.error(`No ${out}: run \`cd contracts && forge build\` first.`);
  process.exit(1);
}
mkdirSync(dest, { recursive: true });
const index = [];
for (const name of contracts) {
  const artifact = JSON.parse(readFileSync(join(out, `${name}.sol`, `${name}.json`), "utf8"));
  const id = name[0].toLowerCase() + name.slice(1) + "Abi";
  writeFileSync(
    join(dest, `${name}.ts`),
    `// Generated by web/scripts/export-abi.mjs from contracts/out/${name}.sol. Do not edit.\nexport const ${id} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`,
  );
  index.push(`export { ${id} } from "./${name}";`);
  console.log(`abi: ${name} (${artifact.abi.length} entries)`);
}
writeFileSync(join(dest, "index.ts"), index.join("\n") + "\n");
