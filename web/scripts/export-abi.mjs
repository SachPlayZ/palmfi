#!/usr/bin/env node
// Exports contract ABIs from contracts/out (run `forge build` in contracts/ first) into web/src/abi/*.ts.
// Usage (from web/): pnpm abi
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "../../contracts/out");
const dest = join(here, "../src/abi");
const contracts = ["Vault", "VaultFactory", "Hub", "ApprovalBook", "NetworkRegistry", "ProtectedToken"];
// The Vault forwards unknown selectors to VaultModule (delegatecall), so the app sees both ABIs at the Vault address.
const merged = { Vault: ["VaultModule"] };

const key = (e) => `${e.type}:${e.name ?? ""}(${(e.inputs ?? []).map((i) => i.type).join(",")})`;
const load = (name) => JSON.parse(readFileSync(join(out, `${name}.sol`, `${name}.json`), "utf8")).abi;
function abiOf(name) {
  const seen = new Map(load(name).map((e) => [key(e), e]));
  for (const extra of merged[name] ?? []) {
    for (const e of load(extra)) if (e.type !== "constructor" && !seen.has(key(e))) seen.set(key(e), e);
  }
  return [...seen.values()];
}

if (!existsSync(out)) {
  console.error(`No ${out}: run \`cd contracts && forge build\` first.`);
  process.exit(1);
}
mkdirSync(dest, { recursive: true });
const index = [];
for (const name of contracts) {
  const abi = abiOf(name);
  const sources = [name, ...(merged[name] ?? [])].map((n) => `contracts/out/${n}.sol`).join(" + ");
  const id = name[0].toLowerCase() + name.slice(1) + "Abi";
  writeFileSync(
    join(dest, `${name}.ts`),
    `// Generated by web/scripts/export-abi.mjs from ${sources}. Do not edit.\nexport const ${id} = ${JSON.stringify(abi, null, 2)} as const;\n`,
  );
  index.push(`export { ${id} } from "./${name}";`);
  console.log(`abi: ${name} (${abi.length} entries)`);
}
writeFileSync(join(dest, "index.ts"), index.join("\n") + "\n");
